"""Prepare a closed, local-only awgproxy profile; never execute imported hooks.

This is a configuration adapter only. It does not start a process or claim that
an AWG runtime is available. The generated bytes contain secrets.
"""

import base64
import binascii
import configparser
import ipaddress
from dataclasses import dataclass, field

_INTERFACE = frozenset({
    'address', 'dns', 'privatekey', 'mtu', 'jc', 'jmin', 'jmax',
    's1', 's2', 's3', 's4', 'h1', 'h2', 'h3', 'h4',
    'i1', 'i2', 'i3', 'i4', 'i5', 'headerprotectionkey',
    'contentpaddingaddition', 'rekeyaftertime', 'rekeytimeout',
    'rejectaftertime', 'keepalivetimeout', 'maxhandshakeattempts',
    'randomtrailers', 'disablecookies',
})
_PEER = frozenset({'publickey', 'presharedkey', 'allowedips', 'endpoint', 'persistentkeepalive'})


@dataclass(frozen=True)
class AwgBridgeConfig:
    payload: bytes = field(repr=False)
    ipv6: bool
    resolver_ipv4: str


def build_awg_bridge_config(raw: str, *, socks_port: int, socks_password: str | None = None) -> AwgBridgeConfig:
    """Translate one .conf into an awgproxy profile with no imported routines.

    Input is not a proof of wire compatibility; the pinned runtime must also
    validate it before it is installed or activated. Never log its output.
    """
    try:
        if not 1024 <= socks_port <= 65535 or len(raw.encode('utf-8')) > 24576:
            raise ValueError
        parser = configparser.ConfigParser(interpolation=None, strict=True, empty_lines_in_values=False)
        parser.read_string(raw.removeprefix('\ufeff'))
        if set(parser.sections()) != {'Interface', 'Peer'} or parser.defaults():
            raise ValueError
        interface, peer = parser['Interface'], parser['Peer']
        if set(interface) - _INTERFACE or set(peer) - _PEER:
            raise ValueError
        if not all(section.get(key, '').strip() for section, key in (
            (interface, 'address'), (interface, 'privatekey'), (interface, 'dns'),
            (peer, 'publickey'), (peer, 'endpoint'), (peer, 'allowedips'),
        )):
            raise ValueError
        # Prevent INI continuation, comments, env expansion and adapter-specific
        # indirection from changing the meaning of generated configuration.
        for section in (interface, peer):
            if any(not value.strip() or any(ord(c) < 32 or ord(c) == 127 for c in value)
                   or value.lstrip().startswith('$') for value in section.values()):
                raise ValueError
        addresses = [ipaddress.ip_interface(value.strip()) for value in interface['address'].split(',')]
        resolvers = [ipaddress.ip_address(value.strip()) for value in interface['dns'].split(',')]
        allowed = [ipaddress.ip_network(value.strip(), strict=False) for value in peer['allowedips'].split(',')]
        if not any(address.version == 4 for address in addresses):
            raise ValueError
        if not any(network.version == 4 and network.prefixlen == 0 for network in allowed):
            raise ValueError
        if not resolvers or any(ip.is_unspecified or ip.is_loopback or ip.is_multicast
                                or ip.is_link_local for ip in resolvers):
            raise ValueError
        endpoint = peer['endpoint'].strip()
        if endpoint.startswith('['):
            closing = endpoint.index(']')
            if endpoint[closing + 1:closing + 2] != ':':
                raise ValueError
            host, port = endpoint[1:closing], endpoint[closing + 2:]
        else:
            host, port = endpoint.rsplit(':', 1)
        endpoint_ip = ipaddress.ip_address(host)
        if (not port.isascii() or not port.isdecimal() or not 1 <= int(port) <= 65535
                or endpoint_ip.is_unspecified or endpoint_ip.is_loopback
                or endpoint_ip.is_multicast or endpoint_ip.is_link_local):
            raise ValueError
        # These fields are keys, not diagnostics. Validate before handing them
        # to a runtime whose parse errors can contain their original values.
        for section, key in ((interface, 'privatekey'), (interface, 'headerprotectionkey'),
                             (peer, 'publickey'), (peer, 'presharedkey')):
            if key in section and len(base64.b64decode(section[key], validate=True)) != 32:
                raise ValueError
        ipv6 = (any(address.version == 6 for address in addresses)
                and any(network.version == 6 and network.prefixlen == 0 for network in allowed))
        if not any(ip.version == 4 for ip in resolvers) or (not ipv6 and any(ip.version == 6 for ip in resolvers)):
            raise ValueError
        # Preserve each supported value, but never carry over unknown sections,
        # executable hooks or proxy routing options from the supplied file.
        lines = []
        for name, section in (('Interface', interface), ('Peer', peer)):
            lines.append(f'[{name}]')
            lines.extend(f'{key} = {value.strip()}' for key, value in section.items())
            lines.append('')
        lines.extend(('[Socks5]', f'BindAddress = 127.0.0.1:{socks_port}'))
        if socks_password is not None:
            if len(socks_password) != 64 or any(c not in '0123456789abcdef' for c in socks_password):
                raise ValueError
            lines.extend(('Username = tempest', f'Password = {socks_password}'))
        lines.append('')
        return AwgBridgeConfig(('\n'.join(lines)).encode(), ipv6,
                               str(next(ip for ip in resolvers if ip.version == 4)))
    except (configparser.Error, ValueError, UnicodeError, binascii.Error):
        raise ValueError('invalid or unsupported AWG profile') from None
